import { expect, test, type Page, type Locator } from '@playwright/test'

async function editor(page: Page, language = 'en-US', theme = 'dark', width = 1440) {
 await page.addInitScript(({ language,theme }) => {
  sessionStorage.setItem('suma-demo-session','1'); localStorage.setItem('suma-language',language); localStorage.setItem('suma-theme',theme); localStorage.setItem('suma-node','local')
  const policy = {mode:'immediate',timezone:'UTC',digest_hour:9,quiet_start:'',quiet_end:'',template:'[Original] {{title}}',fallback_id:'',fallback_chat_id:''}
  const rules = [{id:'r-oom',name:'Container incidents',version:1,config:{events:['container.oom'],severities:[],node_ids:[],group_ids:[],projects:[]}}, {id:'r-nodes',name:'Node availability',version:1,config:{events:['node.offline','node.recovered'],severities:[],node_ids:[],group_ids:[],projects:[]}}]
  const channels = [{id:'subscription-channel',name:'Operations',provider:'feishu_app',enabled:true,version:1,has_secrets:true,config:{app_id:'cli_subscriptions_ui',endpoint:'',chat_id:'',targets:[{chat_id:'oc_operations',name:'On-call team'},{chat_id:'oc_development',name:'Development team',subscription_override:{rule_ids:['r-nodes'],policy:{...policy,mode:'daily',timezone:'Asia/Shanghai'}}}],language,subscription:{rule_ids:['r-oom'],policy},allow_private:false,auto_discover:false,public_url:'https://suma.example'}}]
  sessionStorage.setItem('suma-demo-notifications-v2',JSON.stringify({serial:100,channels,rules,deliveries:[],inbox:{unread:0,items:[]}}))
 },{language,theme})
 await page.setViewportSize({width,height:900}); await page.goto('/settings#notifications'); await page.getByRole('button',{name:'Operations',exact:true}).click()
 return page.getByRole('dialog',{name:language === 'zh-CN' ? '配置通知渠道' : 'Configure channel',exact:true})
}
async function choose(page: Page,sheet: Locator,label: string,option: string) {
 await sheet.getByRole('combobox',{name:label,exact:true}).click(); await page.getByRole('option',{name:option,exact:true}).click()
}
async function snapshot(page: Page) { return page.evaluate(() => JSON.parse(sessionStorage.getItem('suma-demo-notifications-v2') || '{}')) }

test('channel selects existing rules and persists defaults plus newly selected inheriting targets atomically',async ({page}) => {
 const sheet = await editor(page)
 await sheet.getByRole('checkbox',{name:'Private chat · Admin',exact:true}).check()
 await sheet.getByRole('tab',{name:'Subscriptions',exact:true}).click()
 await sheet.getByRole('textbox',{name:'Search available rules',exact:true}).fill('offline')
 await expect(sheet.getByRole('checkbox',{name:'Container incidents',exact:true})).toHaveCount(0)
 await sheet.getByRole('checkbox',{name:'Node availability',exact:true}).check()
 await sheet.getByRole('textbox',{name:'Search available rules',exact:true}).fill('')
 await expect(sheet.getByRole('checkbox',{name:'Container incidents',exact:true})).toBeChecked()
 await choose(page,sheet,'Frequency','Merge over 5 minutes')
 await sheet.getByRole('button',{name:'Save and finish',exact:true}).click()
 await expect(sheet).toBeHidden()
 const data = await snapshot(page)
 expect(data.rules).toHaveLength(2)
 expect(data.channels[0].config.subscription.rule_ids).toEqual(['r-oom','r-nodes'])
 expect(data.channels[0].config.subscription.policy.mode).toBe('merge')
 expect(data.channels[0].config.targets).toHaveLength(3)
 expect(data.channels[0].config.targets[2].subscription_override).toBeUndefined()
 expect(data.channels[0].config.targets[1].subscription_override.rule_ids).toEqual(['r-nodes'])
})

