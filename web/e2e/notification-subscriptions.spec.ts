test('a concurrent channel save rejects stale subscriptions while preserving the draft',async ({page}) => {
 const sheet = await editor(page);await sheet.getByRole('tab',{name:'Subscriptions',exact:true}).click()
 await sheet.getByRole('checkbox',{name:'Node availability',exact:true}).check()
 await page.evaluate(async () => {
  // @ts-expect-error Vite exposes the demo API module.
  const {api} = await import('/src/lib/api.ts')
  const channels = await api('/notifications/channels'),channel=channels[0]
  await api(`/notifications/channels/${channel.id}`,{method:'PUT',body:JSON.stringify({...channel,name:'Saved elsewhere'})})
 })
 await sheet.getByRole('button',{name:'Save and finish',exact:true}).click()
 await expect(sheet).toBeVisible()
 await expect(sheet.getByRole('alert')).toContainText('Configuration changed')
 await expect(sheet.getByRole('checkbox',{name:'Node availability',exact:true})).toBeChecked()
 const data = await snapshot(page)
 expect(data.channels[0].name).toBe('Saved elsewhere')
 expect(data.channels[0].config.subscription.rule_ids).toEqual(['r-oom'])
})

