async function seedChannels(page: Page, count = 3) {
 await page.addInitScript(count => {
  const key = 'suma-demo-notifications-v2'
  if (sessionStorage.getItem(key)) return
  const channels = Array.from({ length: count }, (_, index) => ({
   id: `list-channel-${index}`, name: ['Operations alerts', 'Telegram on-call', 'Webhook integrations with a deliberately long notification channel name'][index] || `Notification ${String(index + 1).padStart(2, '0')}`,
   provider: ['feishu_app', 'telegram', 'webhook'][index % 3], enabled: index !== 1, version: 1, has_secrets: true,
   config: { endpoint: '', chat_id: index % 3 === 1 ? '123456' : '', app_id: index % 3 === 0 ? `cli_list_${index}` : '', targets: index % 3 === 0 ? [{ chat_id: 'oc_operations', name: 'Operations' }] : [], language: 'en-US', subscription: { rule_ids: [], policy: { mode: 'immediate', timezone: 'UTC', digest_hour: 9, quiet_start: '', quiet_end: '', template: '', fallback_id: '', fallback_chat_id: '' } }, allow_private: false, auto_discover: false, public_url: '' },
   last_sent_at: index === 1 ? undefined : '2026-10-11T00:00:00Z', last_error: index === 2 ? 'Connection timed out; delivery will retry.' : '',
  }))
  sessionStorage.setItem(key, JSON.stringify({ serial: count, channels, rules: [], deliveries: [], inbox: { unread: 1, items: [{ id: 'demo-event', type: 'container.oom', severity: 'error', time: '2026-10-11T00:00:00Z', node_id: 'local', node_name: 'Local', resource_id: 'redis-main', title: 'Container OOM', message: 'The container exceeded its memory limit.', task_id: '', read: false }] } }))
 }, count)
}
