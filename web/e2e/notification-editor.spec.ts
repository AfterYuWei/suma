import { expect, test, type Page } from '@playwright/test'

async function savedEditor(page: Page, targets = [{ chat_id: 'oc_operations', name: 'Operations' }], language = 'en-US', theme = 'dark', width = 390) {
 await page.addInitScript(({ targets, language, theme }) => {
  sessionStorage.setItem('suma-demo-session', '1')
  localStorage.setItem('suma-language', language)
  localStorage.setItem('suma-theme', theme)
  localStorage.setItem('suma-node', 'local')
  sessionStorage.setItem('suma-demo-notifications-v2', JSON.stringify({ serial: 1, channels: [{ id: 'editor-channel', name: 'Operations alerts', provider: 'feishu_app', enabled: true, version: 1, has_secrets: true, config: { app_id: 'cli_editor', endpoint: '', chat_id: '', targets, language, subscription: { rule_ids: [], policy: { mode: 'immediate', timezone: 'UTC', digest_hour: 9, quiet_start: '', quiet_end: '', template: '', fallback_id: '', fallback_chat_id: '' } }, allow_private: false, auto_discover: false, public_url: '' } }], rules: [], deliveries: [], inbox: { unread: 0, items: [] } }))
 }, { targets, language, theme })
 await page.setViewportSize({ width, height: 900 })
 await page.goto('/settings#notifications')
 await page.getByRole('button', { name: 'Operations alerts', exact: true }).click()
 return page.getByRole('dialog', { name: language === 'zh-CN' ? '配置通知渠道' : 'Configure channel', exact: true })
}

async function schemaAvailable(page: Page, available: boolean) {
 await page.evaluate(async available => {
  // @ts-expect-error Vite exposes the demo fixture module in the browser.
  const { setDemoNotificationSchemaAvailable } = await import('/src/features/notifications/mock.ts')
  setDemoNotificationSchemaAvailable(available)
 }, available)
}

async function snapshot(page: Page) {
 return page.evaluate(() => JSON.parse(sessionStorage.getItem('suma-demo-notifications-v2') || '{}'))
}

test('subscription tab preserves connection draft and saving failure keeps both views editable', async ({ page }) => {
 const sheet = await savedEditor(page)
 await sheet.getByRole('checkbox', { name: 'Private chat · Admin', exact: true }).check()
 await sheet.getByRole('button', { name: 'Subscription settings', exact: true }).click()
 await expect(sheet.getByRole('tab', { name: 'Subscriptions', exact: true })).toHaveAttribute('aria-selected','true')
 await sheet.getByLabel('Subscription timezone', { exact: true }).fill('Asia/Shanghai')
 await schemaAvailable(page,false)
 await sheet.getByRole('button', { name: 'Save channel', exact: true }).click()
 await expect(sheet.getByRole('alert')).toContainText('fresh PostgreSQL database')
 await expect(sheet.getByLabel('Subscription timezone', { exact: true })).toHaveValue('Asia/Shanghai')
 await sheet.getByRole('tab', { name: 'Connection', exact: true }).click()
 await expect(sheet.getByRole('checkbox', { name: 'Private chat · Admin', exact: true })).toBeChecked()
 await expect(sheet.getByRole('status', { name: 'Save status', exact: true })).toHaveText('Unsaved changes')
 let data = await snapshot(page); expect(data.channels[0].config.targets).toHaveLength(1)
 await schemaAvailable(page,true)
 await sheet.getByRole('button', { name: 'Save channel', exact: true }).click()
 await sheet.getByRole('tab', { name: 'Subscriptions', exact: true }).click()
 await expect(sheet.getByLabel('Subscription timezone', { exact: true })).toHaveValue('Asia/Shanghai')
 data = await snapshot(page); expect(data.channels[0].config.targets).toHaveLength(2); expect(data.channels[0].version).toBe(2)
 expect(data.channels[0].config.subscription.policy.timezone).toBe('Asia/Shanghai')
 expect(data.deliveries).toHaveLength(0)
})

test('save and finish retains the draft after failure and closes only after persisting channel state', async ({ page }) => {
 const sheet = await savedEditor(page)
 await sheet.getByLabel('Channel name', { exact: true }).fill('Renamed alerts')
 await sheet.getByRole('switch', { name: 'Enable channel', exact: true }).click()
 await schemaAvailable(page, false)
 await sheet.getByRole('button', { name: 'Save and finish', exact: true }).click()
 await expect(sheet.getByRole('alert')).toContainText('fresh PostgreSQL database')
 await expect(sheet).toBeVisible()
 await expect(sheet.getByLabel('Channel name', { exact: true })).toHaveValue('Renamed alerts')
 await expect(sheet.getByRole('switch', { name: 'Enable channel', exact: true })).not.toBeChecked()
 let data = await snapshot(page)
 expect(data.channels[0].name).toBe('Operations alerts')
 expect(data.channels[0].enabled).toBe(true)
 await schemaAvailable(page, true)
 await sheet.getByRole('button', { name: 'Save and finish', exact: true }).click()
 await expect(sheet).toBeHidden()
 await page.getByRole('button', { name: 'Renamed alerts', exact: true }).click()
 await expect(sheet.getByRole('switch', { name: 'Enable channel', exact: true })).not.toBeChecked()
 await expect(sheet.getByRole('status', { name: 'Save status', exact: true })).toHaveText('Saved')
 data = await snapshot(page)
 expect(data.channels).toHaveLength(1)
 expect(data.channels[0].name).toBe('Renamed alerts')
 expect(data.channels[0].enabled).toBe(false)
 expect(data.deliveries).toHaveLength(0)
})

test('recipient notes edit on demand, Escape cancels without closing and Enter commits', async ({ page }) => {
 const sheet = await savedEditor(page)
 await expect(sheet.getByLabel('Recipient name oc_operations', { exact: true })).toHaveCount(0)
 await sheet.getByRole('button', { name: 'Edit recipient name Operations', exact: true }).click()
 const input = sheet.getByLabel('Recipient name oc_operations', { exact: true })
 await input.fill('Temporary name')
 await input.press('Escape')
 await expect(sheet).toBeVisible()
 await expect(sheet.getByRole('button', { name: 'Edit recipient name Operations', exact: true })).toBeVisible()
 await expect(sheet.getByRole('status', { name: 'Save status', exact: true })).toHaveText('Saved')
 await sheet.getByRole('button', { name: 'Edit recipient name Operations', exact: true }).click()
 await input.fill('On-call team')
 await input.press('Enter')
 await expect(sheet.getByRole('button', { name: 'Edit recipient name On-call team', exact: true })).toBeVisible()
 await expect(sheet.getByRole('status', { name: 'Save status', exact: true })).toHaveText('Unsaved changes')
 await sheet.getByRole('button', { name: 'Save and finish', exact: true }).click()
 await expect(sheet).toBeHidden()
 const data = await snapshot(page)
 expect(data.channels[0].config.targets).toEqual([{ chat_id: 'oc_operations', name: 'On-call team' }])
})

