import { expect, test, type Page } from '@playwright/test'

async function openDraft(page: Page, name: string, zh = false, theme = 'dark') {
  await page.addInitScript(({ zh, theme }) => {
    sessionStorage.setItem('suma-demo-session', '1')
    localStorage.setItem('suma-language', zh ? 'zh-CN' : 'en-US')
    localStorage.setItem('suma-theme', theme)
    localStorage.setItem('suma-node', 'local')
  }, { zh, theme })
  await page.goto('/continuous-delivery/new/project')
  const form = page.getByRole('form', { name: zh ? '新建交付项目配置' : 'New delivery project configuration', exact: true })
  await form.getByLabel(zh ? '项目名称' : 'Project name', { exact: true }).fill(name)
  await form.getByLabel('Git Clone URL', { exact: true }).fill('https://git.example.test/deploy.git')
  return form
}

for (const zh of [false, true]) for (const theme of ['dark', 'light']) for (const width of [390, 1440]) {
  test(`quick environment import ${zh ? 'zh' : 'en'} ${theme} ${width}`, async ({ page }) => {
    await page.setViewportSize({ width, height: 900 })
    const form = await openDraft(page, `quick-${zh ? 'zh' : 'en'}-${theme}-${width}`, zh, theme)
    await form.getByRole('button', { name: zh ? '添加环境变量' : 'Add variable', exact: true }).click()
    await form.getByLabel(zh ? '变量名称 1' : 'Variable name 1', { exact: true }).fill('APP_ENV')
    await form.getByLabel(zh ? '变量值 1' : 'Variable value 1', { exact: true }).fill('keep-existing')
    const trigger = form.getByRole('button', { name: zh ? '快速添加' : 'Quick add', exact: true })
    await trigger.click()
    const dialog = page.getByRole('dialog', { name: zh ? '快速添加环境变量' : 'Quick add environment variables', exact: true })
    const input = dialog.getByLabel('KEY=VALUE', { exact: true })
    await input.fill('# comment\r\nexport APP_ENV=replace-only-if-selected\r\nPASSWORD="test-only-secret=${literal}\\path"\r\nEMPTY=\r\n')
    await expect(dialog.getByRole('status')).toContainText(zh ? '新增 2 项，替换 0 项，保留 1 项' : 'Add 2, replace 0, keep 1')
    await expect(dialog.locator('#cd-quick-environment-feedback')).not.toContainText('test-only-secret')
    expect(await input.evaluate(element => getComputedStyle(element).getPropertyValue('-webkit-text-security'))).toBe('disc')
    await dialog.getByRole('button', { name: zh ? '显示输入值' : 'Show entered values', exact: true }).click()
    expect(await input.evaluate(element => getComputedStyle(element).getPropertyValue('-webkit-text-security'))).not.toBe('disc')
    await dialog.getByRole('button', { name: zh ? '隐藏输入值' : 'Hide entered values', exact: true }).click()
    const bounds = await dialog.boundingBox()
    expect(bounds!.x).toBeGreaterThanOrEqual(0)
    expect(bounds!.x + bounds!.width).toBeLessThanOrEqual(width)
    expect(bounds!.y).toBeGreaterThanOrEqual(0)
    expect(bounds!.y + bounds!.height).toBeLessThanOrEqual(900)
    expect(await dialog.evaluate(element => element.scrollWidth <= element.clientWidth)).toBe(true)
    await dialog.screenshot({ path: `/tmp/suma-cd-quick-add-${zh ? 'zh' : 'en'}-${theme}-${width}.png` })
    if (!zh && theme === 'dark' && width === 1440) await input.press('ControlOrMeta+Enter')
    else await dialog.getByRole('button', { name: zh ? '添加到表单' : 'Add to form', exact: true }).click()
    await expect(dialog).toHaveCount(0)
    await expect(page).toHaveURL('/continuous-delivery/new/project')
    await expect(form.getByLabel(zh ? '变量值 1' : 'Variable value 1', { exact: true })).toHaveValue('keep-existing')
    await expect(form.getByLabel(zh ? '变量值 2' : 'Variable value 2', { exact: true })).toHaveValue('test-only-secret=${literal}\\path')
    await expect(form.getByLabel(zh ? '变量值 2' : 'Variable value 2', { exact: true })).toHaveAttribute('type', 'password')
    await expect(form.getByLabel(zh ? '变量值 3' : 'Variable value 3', { exact: true })).toHaveValue('')
    await expect(form.getByRole('checkbox', { name: zh ? '使用空值 3' : 'Use empty value 3', exact: true })).toBeChecked()
    await trigger.click()
    await expect(input).toHaveValue('')
    await expect(dialog.getByRole('checkbox')).not.toBeChecked()
    await input.press('Escape')
    await expect(dialog).toHaveCount(0)
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
    await form.getByRole('button', { name: zh ? '创建交付项目' : 'Create delivery project', exact: true }).click()
    await expect(page).toHaveURL(/\/continuous-delivery\/quick-/)
    await page.getByRole('tab', { name: zh ? '设置' : 'Settings', exact: true }).click()
    const edit = page.getByRole('form', { name: zh ? '交付项目配置' : 'Delivery project configuration', exact: true })
    await expect(edit.getByTestId('cd-environment-row')).toHaveCount(3)
    await expect(edit.getByLabel(zh ? '变量值 2' : 'Variable value 2', { exact: true })).toHaveValue('')
  })
}

test('quick add replaces saved names only when selected and cancellation clears private input', async ({ page }) => {
  const form = await openDraft(page, 'quick-saved')
  await form.getByRole('button', { name: 'Quick add', exact: true }).click()
  const dialog = page.getByRole('dialog', { name: 'Quick add environment variables', exact: true })
  const input = dialog.getByLabel('KEY=VALUE', { exact: true })
  await input.fill('PASSWORD=original')
  await dialog.getByRole('button', { name: 'Add to form', exact: true }).click()
  await form.getByRole('button', { name: 'Create delivery project', exact: true }).click()
  await expect(page).toHaveURL('/continuous-delivery/quick-saved')
  await page.getByRole('tab', { name: 'Settings', exact: true }).click()
  const edit = page.getByRole('form', { name: 'Delivery project configuration', exact: true })
  await edit.getByRole('button', { name: 'Quick add', exact: true }).click()
  await input.fill('PASSWORD=replacement\nNEW=added')
  await dialog.getByRole('button', { name: 'Add to form', exact: true }).click()
  await expect(edit.getByLabel('Variable value 1', { exact: true })).toHaveValue('')
  await expect(edit.getByLabel('Variable value 1', { exact: true })).toHaveAttribute('placeholder', 'Saved · show to view')
  await edit.getByRole('button', { name: 'Quick add', exact: true }).click()
  await input.fill('PASSWORD=replacement')
  await expect(dialog.getByRole('button', { name: 'Add to form', exact: true })).toBeDisabled()
  await dialog.getByRole('checkbox', { name: 'Replace matching variables', exact: true }).click()
  await expect(dialog.getByRole('status')).toContainText('Add 0, replace 1, keep 0')
  await dialog.getByRole('button', { name: 'Add to form', exact: true }).click()
  await expect(edit.getByLabel('Variable value 1', { exact: true })).toHaveValue('replacement')
  await edit.getByRole('button', { name: 'Quick add', exact: true }).click()
  await input.fill('CANCELLED=private-draft')
  await dialog.getByRole('button', { name: 'Cancel', exact: true }).click()
  await expect(edit.getByTestId('cd-environment-row')).toHaveCount(2)
  await edit.getByRole('button', { name: 'Quick add', exact: true }).click()
  await expect(input).toHaveValue('')
  await expect(dialog.getByRole('checkbox')).not.toBeChecked()
})

test('quick add reports line errors without private values and makes no partial changes', async ({ page }) => {
  const form = await openDraft(page, 'quick-invalid')
  await form.getByRole('button', { name: 'Quick add', exact: true }).click()
  const dialog = page.getByRole('dialog', { name: 'Quick add environment variables', exact: true })
  const input = dialog.getByLabel('KEY=VALUE', { exact: true })
  for (const source of ['VALID=okay\nprivate-invalid-line', 'DUP=one\nDUP=private-invalid-line', 'DOCKER_HOST=private-invalid-line', 'VALUE="private-invalid-line']) {
    await input.fill(source)
    await expect(dialog.getByRole('alert')).toContainText(/Line \d+/)
    await expect(dialog.getByRole('alert')).not.toContainText('private-invalid-line')
    await expect(dialog.getByRole('button', { name: 'Add to form', exact: true })).toBeDisabled()
    await expect(form.getByTestId('cd-environment-row')).toHaveCount(0)
  }
  await input.fill('FIXED=okay')
  await dialog.getByRole('button', { name: 'Add to form', exact: true }).click()
  await expect(form.getByTestId('cd-environment-row')).toHaveCount(1)
  await expect(form.getByLabel('Variable name 1', { exact: true })).toHaveValue('FIXED')
  await expect(page).toHaveURL('/continuous-delivery/new/project')
})
