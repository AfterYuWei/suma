import { expect, test } from '@playwright/test'

for (const language of ['en-US', 'zh-CN']) for (const theme of ['dark', 'light']) for (const width of [390, 1440]) {
  test(`Git connection draft ${language} ${theme} ${width}`, async ({ page }) => {
    await page.addInitScript(({ language, theme }) => {
      sessionStorage.setItem('suma-demo-session', '1')
      localStorage.setItem('suma-language', language)
      localStorage.setItem('suma-theme', theme)
    }, { language, theme })
    await page.setViewportSize({ width, height: 1000 })
    const zh = language === 'zh-CN'
    await page.goto('/continuous-delivery/new/project')
    const button = page.getByRole('button', { name: zh ? '测试连接' : 'Test connection', exact: true })
    await expect(button).toBeDisabled()
    const url = page.getByLabel('Git Clone URL', { exact: true })
    await url.fill('https://cnb.cool/team/missing-repo')
    await button.click()
    const error = page.getByRole('alert').filter({ hasText: zh ? '连接失败' : 'Connection failed' })
    await expect(error).toContainText('404')
    await expect(error).toContainText(zh ? '私有仓库' : 'private repository')
    await url.fill('https://cnb.cool/team/repo')
    await expect(error).toHaveCount(0)
    await button.click()
    const success = page.getByRole('status').filter({ hasText: zh ? '连接成功' : 'Connection successful' })
    await expect(success).toContainText('7a31f0c8')
    await success.focus()
    await page.keyboard.press('Shift+Tab')
    await page.keyboard.press('Tab')
    await expect(page.getByRole('tooltip')).toContainText('branch:main')
    await expect(page.getByRole('tooltip')).toContainText('7a31f0c87aa1')
    await page.keyboard.press('Escape')
    if (width === 1440) {
      const statusBounds = await success.boundingBox(), buttonBounds = await button.boundingBox()
      expect(Math.abs(statusBounds!.y + statusBounds!.height / 2 - buttonBounds!.y - buttonBounds!.height / 2)).toBeLessThan(2)
    }
    await expect(page.getByLabel(zh ? '项目名称' : 'Project name', { exact: true })).toHaveValue('')
    await expect(page).toHaveURL('/continuous-delivery/new/project')
    await page.getByLabel(zh ? '引用名称' : 'Reference', { exact: true }).fill('missing')
    await expect(success).toHaveCount(0)
    await button.click()
    await expect(error).toContainText('remote branch "missing" was not found')
    await page.getByRole('combobox', { name: zh ? '引用类型' : 'Reference type', exact: true }).click()
    await page.getByRole('option', { name: 'Commit', exact: true }).click()
    await page.getByLabel('Commit SHA', { exact: true }).fill('a'.repeat(40))
    await button.click()
    await success.focus()
    await page.keyboard.press('Shift+Tab')
    await page.keyboard.press('Tab')
    await expect(page.getByRole('tooltip')).toContainText(zh ? '指定 Commit 将在同步时验证' : 'specified commit will be verified during sync')
    await page.keyboard.press('Escape')
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
    await button.scrollIntoViewIfNeeded()
    await page.screenshot({ path: `/tmp/suma-cd-connection-${language}-${theme}-${width}.png` })
  })
}

test('existing project tests the edited credential without saving configuration', async ({ page }) => {
  await page.addInitScript(() => {
    sessionStorage.setItem('suma-demo-session', '1')
    localStorage.setItem('suma-language', 'en-US')
  })
  await page.goto('/continuous-delivery/gateway-prod')
  await page.getByRole('tab', { name: 'Settings', exact: true }).click()
  const url = page.getByLabel('Git Clone URL', { exact: true })
  const original = await url.inputValue()
  await url.fill('https://cnb.cool/team/repo')
  await page.getByRole('combobox', { name: 'Authentication source', exact: true }).click()
  await page.getByRole('option', { name: 'Use a project credential', exact: true }).click()
  await page.getByLabel('Name', { exact: true }).fill('draft')
  await page.getByLabel('Token', { exact: true }).fill('private-draft-token')
  await page.getByRole('button', { name: 'Test connection', exact: true }).click()
  await expect(page.getByRole('status').filter({ hasText: 'Connection successful' })).toBeVisible()
  await expect(page.getByLabel('Token', { exact: true })).toHaveValue('private-draft-token')
  expect(await page.evaluate(() => document.body.innerText)).not.toContain('private-draft-token')
  const saved = await page.evaluate(async () => {
    // @ts-expect-error Vite serves source imports in the browser.
    const { api } = await import('/src/lib/api.ts')
    return api('/delivery-projects/gateway-prod/configuration')
  })
  expect(saved.repository.clone_url).toBe(original)
  expect(saved.repository.authentication.source).toBe('center')
})
