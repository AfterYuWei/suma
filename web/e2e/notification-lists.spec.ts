for (const width of [360, 1440]) for (const language of ['zh-CN', 'en-US']) for (const theme of ['dark', 'light']) {
 test(`all notification lists ${language} ${theme} ${width}`, async ({ page }) => {
  await seed(page, language, theme)
  await page.setViewportSize({ width, height: 900 })
  const zh = language === 'zh-CN', errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto('/settings#notifications')
  for (const tab of ['channels', 'rules', 'deliveries']) {
   const name = tab === 'channels' ? zh ? '渠道' : 'Channels' : tab === 'rules' ? zh ? '通知规则' : 'Rules' : zh ? '发送记录' : 'Deliveries'
   await page.getByRole('tab', { name, exact: true }).click()
   const tableName = tab === 'channels' ? zh ? '通知渠道列表' : 'Notification channels' : tab === 'rules' ? zh ? '通知规则列表' : 'Notification rules' : zh ? '发送记录列表' : 'Notification deliveries'
   const table = page.getByRole('table', { name: tableName, exact: true })
   await expect(table).toBeVisible()
   if (tab === 'rules') {
    await expect(table.getByRole('columnheader', { name: zh ? '状态' : 'Status', exact: true })).toHaveCount(0)
    await table.getByRole('button', { name: 'Account security', exact: true }).click()
    const ruleEditor = page.getByRole('dialog', { name: zh ? '通知规则' : 'Notification rule', exact: true })
    await expect(ruleEditor.getByRole('checkbox', { name: zh ? '启用规则' : 'Enable rule', exact: true })).toHaveCount(0)
    await expect(ruleEditor.getByText(zh ? /勾选并保存规则后即生效/ : /Rules take effect when selected and saved/)).toBeVisible()
    await page.keyboard.press('Escape')
    await table.getByRole('button', { name: `${zh ? '规则操作' : 'Rule actions'} Account security`, exact: true }).click()
    const menu = page.getByRole('menu', { name: `${zh ? '规则操作' : 'Rule actions'} Account security`, exact: true })
    await expect(menu).toBeVisible()
    await expect(page.getByRole('menuitem', { name: zh ? '暂停' : 'Pause', exact: true })).toHaveCount(0)
    await expect(page.getByRole('menuitem', { name: zh ? '启用' : 'Enable', exact: true })).toHaveCount(0)
    await menu.press('Escape')
    await expect(menu).toBeHidden()
   }
   await expect(page.getByRole('navigation', { name: zh ? '列表分页' : 'List pagination', exact: true })).toBeVisible()
   await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
   await page.screenshot({ path: `/tmp/suma-${tab}-list-${language}-${theme}-${width}.png`, fullPage: true })
  }
  expect(errors).toEqual([])
 })
}
