import { expect, test, type Page } from '@playwright/test'

async function seed(page: Page, language = 'en-US', theme = 'dark', count = 31) {
 await page.addInitScript(({ language, theme, count }) => {
  sessionStorage.setItem('suma-demo-session', '1')
  localStorage.setItem('suma-language', language)
  localStorage.setItem('suma-theme', theme)
  localStorage.setItem('suma-node', 'local')
  localStorage.setItem('suma-list-page-size', '10')
  const channels = [
   { id: 'list-feishu', name: 'Operations bot', provider: 'feishu_app', enabled: true, version: 1, has_secrets: true, config: { app_id: 'cli_lists', endpoint: '', chat_id: '', targets: [{ chat_id: 'oc_operations', name: 'Operations team' }], language, subscription: { rule_ids: [], policy: { mode: 'immediate', timezone: 'UTC', digest_hour: 9, quiet_start: '', quiet_end: '', template: '', fallback_id: '', fallback_chat_id: '' } }, allow_private: false, auto_discover: false, public_url: '' } },
   { id: 'list-webhook', name: 'Production Webhook with a deliberately long destination name', provider: 'webhook', enabled: true, version: 1, has_secrets: true, config: { app_id: '', endpoint: '', chat_id: '', targets: [], language, subscription: { rule_ids: [], policy: { mode: 'immediate', timezone: 'UTC', digest_hour: 9, quiet_start: '', quiet_end: '', template: '', fallback_id: '', fallback_chat_id: '' } }, allow_private: false, auto_discover: false, public_url: '' } },
  ]
  const rules = Array.from({ length: count }, (_, index) => ({ id: `rule-${index}`, name: ['Account security', 'Important incidents', 'A notification rule with a deliberately long descriptive name for production changes'][index] || `Rule ${index}`, version: 1, config: { events: index === 0 ? ['auth.login'] : ['container.oom','node.offline'], severities: [], node_ids: [], group_ids: [], projects: index === 2 ? ['gateway-prod'] : [] } }))
  for (const [index,channel] of channels.entries()) channel.config.subscription.rule_ids = rules.filter((_,i) => i%2 === index).map(rule => rule.id) as never[]
  const deliveries = Array.from({ length: count }, (_, index) => ({ id:`delivery-${index}`,channel_id:index === 3 ? 'deleted-channel' : index%2 ? 'list-webhook' : 'list-feishu',chat_id:index%2 ? '' : 'oc_operations',matched_rules:index === 1 ? [] : [{id:index === 2 ? 'deleted-rule' : `rule-${index}`,name:index === 2 ? 'Historical rule name' : rules[index].name,version:1}],event_count:1,source:'event',status:['failed','sent','retry','suppressed','pending','sending'][index%6],reason:index === 0 ? 'Request timed out; the provider returned an unavailable response.' : index === 3 ? 'channel deleted' : index === 2 ? 'Connection timed out; delivery will retry.' : '',attempts:index%6,due_at:'2026-10-11T04:00:00Z',created_at:'2026-10-11T03:00:00Z'}))
  if (deliveries.length) deliveries[0].matched_rules.push({id:'historical-overlap',name:'Historical overlapping rule',version:1})
  sessionStorage.setItem('suma-demo-notifications-v2', JSON.stringify({ serial: 100, channels, rules, deliveries, inbox: { unread: 0, items: [] } }))
 }, { language, theme, count })
}

test('rules search events and destinations, reset pagination and retain editing and confirmed deletion without rule toggles', async ({ page }) => {
 await seed(page)
 await page.goto('/settings#notifications?tab=rules')
 const table = page.getByRole('table', { name: 'Notification rules', exact: true }), search = page.getByRole('textbox', { name: 'Search notification rules', exact: true }), pages = page.getByRole('navigation', { name: 'List pagination', exact: true })
 await expect(table.locator('tbody tr')).toHaveCount(10)
 await pages.getByRole('button', { name: 'Next page', exact: true }).click()
 await expect(pages.getByText('2 / 4', { exact: true })).toBeVisible()
 await search.fill('Account security')
 await expect(pages.getByText('1 / 1', { exact: true })).toBeVisible()
 await table.getByRole('button', { name: 'Account security', exact: true }).click()
 const editor = page.getByRole('dialog', { name: 'Notification rule', exact: true })
 await expect(editor.getByLabel('Rule name', { exact: true })).toHaveValue('Account security')
 await page.keyboard.press('Escape')
 const actions = table.getByRole('button', { name: 'Rule actions Account security', exact: true })
 await expect(editor.getByRole('checkbox', { name: 'Enable rule', exact: true })).toHaveCount(0)
 await expect(table.getByRole('columnheader', { name: 'Status', exact: true })).toHaveCount(0)
 await actions.click()
 await expect(page.getByRole('menuitem', { name: 'Pause', exact: true })).toHaveCount(0)
 await expect(page.getByRole('menuitem', { name: 'Enable', exact: true })).toHaveCount(0)
 await page.keyboard.press('Escape')
 await search.fill('Container OOM')
 await expect(table.getByRole('button', { name: 'Important incidents', exact: true })).toBeVisible()
 await search.fill('Production Webhook')
 await expect(table.getByRole('button', { name: 'Important incidents', exact: true })).toBeVisible()
 await search.fill('nothing matches')
 await expect(page.getByText('No matching notification rules', { exact: true })).toBeVisible()
 await page.getByRole('button', { name: 'Clear search', exact: true }).click()
 await table.getByRole('button', { name: 'Rule actions Account security', exact: true }).click()
 await page.getByRole('menuitem', { name: 'Delete', exact: true }).click()
 const confirmation = page.getByRole('dialog', { name: 'Delete Account security?', exact: true })
 await expect(confirmation).toBeVisible()
 const beforeDelete = await page.evaluate(() => JSON.parse(sessionStorage.getItem('suma-demo-notifications-v2') || '{}'))
 expect(beforeDelete.rules.some((rule: { id: string }) => rule.id === 'rule-0')).toBe(true)
 await confirmation.getByRole('button', { name: 'Delete', exact: true }).click()
 await expect(table.getByRole('button', { name: 'Account security', exact: true })).toHaveCount(0)
 await expect(pages.getByText('30 items', { exact: true })).toBeVisible()
})

test('delivery records search recipient, rule and status and resend creates a separate pending record', async ({ page }) => {
 await seed(page)
 await page.goto('/settings#notifications?tab=deliveries')
 const table = page.getByRole('table', { name: 'Notification deliveries', exact: true }), search = page.getByRole('textbox', { name: 'Search notification deliveries', exact: true }), pages = page.getByRole('navigation', { name: 'List pagination', exact: true })
 await expect(table.locator('tbody tr')).toHaveCount(10)
 await expect(table.getByText('Historical rule name', { exact: true })).toBeVisible()
 await expect(table.getByText('No linked rule', { exact: true })).toBeVisible()
 await pages.getByRole('button', { name: 'Next page', exact: true }).click()
 await search.fill('oc_operations')
 await expect(pages.getByText('1 / 2', { exact: true })).toBeVisible()
 await search.fill('Account security')
 await expect(table.locator('tbody tr')).toHaveCount(1)
 await expect(table.getByText('Failed', { exact: true })).toBeVisible()
 await table.getByText('2 matching rules',{exact:true}).click()
 await expect(table.getByText('Historical overlapping rule',{exact:false})).toBeVisible()
 await table.getByRole('button', { name: 'Delivery actions delivery-0', exact: true }).click()
 await page.getByRole('menuitem', { name: 'Resend', exact: true }).click()
 await expect(table.locator('tbody tr')).toHaveCount(2)
 await expect(table.getByText('Pending', { exact: true })).toBeVisible()
 const data = await page.evaluate(() => JSON.parse(sessionStorage.getItem('suma-demo-notifications-v2') || '{}'))
 expect(data.deliveries).toHaveLength(32)
 expect(data.deliveries[0].id).not.toBe('delivery-0')
 expect(data.deliveries[0].status).toBe('pending')
 expect(data.deliveries.find((row: { id: string }) => row.id === 'delivery-0').status).toBe('failed')
 await search.fill('Retrying')
 await expect(table.getByText('Retrying', { exact: true }).first()).toBeVisible()
 await search.fill('nothing matches')
 await expect(page.getByText('No matching deliveries', { exact: true })).toBeVisible()
 await page.getByRole('tab', { name: 'Rules', exact: true }).click()
 await expect(page.getByRole('textbox', { name: 'Search notification rules', exact: true })).toHaveValue('')
 await page.getByRole('tab', { name: 'Deliveries', exact: true }).click()
 await expect(search).toHaveValue('nothing matches')
})

