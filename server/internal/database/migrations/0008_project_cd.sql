CREATE TABLE project_cds (
 id bigserial PRIMARY KEY,
 node_id varchar(64) NOT NULL,
 project_name varchar(128) NOT NULL,
 enabled boolean NOT NULL DEFAULT false,
 revision bigint NOT NULL DEFAULT 1,
 repository_json text NOT NULL DEFAULT '{}',
 git_credential_id bigint,
 credential_ciphertext bytea,
 environment_ciphertext bytea,
 registry_credential_ids_json text NOT NULL DEFAULT '[]',
 deployment_timeout integer NOT NULL DEFAULT 120,
 automation_enabled boolean NOT NULL DEFAULT false,
 initial_application_required boolean NOT NULL DEFAULT true,
 sync_interval_seconds integer NOT NULL DEFAULT 300,
 webhook_enabled boolean NOT NULL DEFAULT false,
 webhook_id varchar(64) NOT NULL UNIQUE,
 webhook_secret bytea,
 candidate_record_id bigint,
 applied_record_id bigint,
 failed_fingerprint varchar(128) NOT NULL DEFAULT '',
 last_check_at timestamptz,
 created_at timestamptz NOT NULL DEFAULT now(),
 updated_at timestamptz NOT NULL DEFAULT now(),
 CONSTRAINT idx_project_cd_identity UNIQUE(node_id,project_name)
);
CREATE TABLE project_cd_records (
 id bigserial PRIMARY KEY,
 project_cd_id bigint NOT NULL REFERENCES project_cds(id),
 operation varchar(24) NOT NULL,
 trigger varchar(24) NOT NULL,
 status varchar(24) NOT NULL,
 task_id varchar(36) NOT NULL DEFAULT '',
 actor text NOT NULL DEFAULT '',
 revision bigint NOT NULL,
 commit_sha varchar(64) NOT NULL DEFAULT '',
 commit_message text NOT NULL DEFAULT '',
 config_hash varchar(64) NOT NULL DEFAULT '',
 snapshot_ciphertext bytea,
 failure_reason text NOT NULL DEFAULT '',
 created_at timestamptz NOT NULL DEFAULT now(),
 finished_at timestamptz
);
CREATE INDEX idx_project_cd_records_project ON project_cd_records(project_cd_id,id DESC);
